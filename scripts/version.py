#!/usr/bin/env python3
"""Single-source version management for qq-notifier.

The ``version`` file at the repository root is the only source of truth.
``check`` reports drift between it and the derived files; ``update`` rewrites
them, optionally committing and tagging the release.

    python scripts/version.py check
    python scripts/version.py update v1.4.0 [--dry-run] [--tag]

Derived files:

    version                     vMAJOR.MINOR.PATCH
    package.json                MAJOR.MINOR.PATCH
    python/qq_notifier.py       __version__ = "MAJOR.MINOR.PATCH" and
                                "Version: vMAJOR.MINOR.PATCH" in the docstring

``package-lock.json`` is generated by npm and is intentionally not touched;
``/health`` derives its version from ``package.json`` at runtime.
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

VERSION_PATTERN = re.compile(r"^v(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)$")
MODULE_VERSION_PATTERN = re.compile(r'^__version__ = "(\d+\.\d+\.\d+)"$', re.MULTILINE)
DOCSTRING_VERSION_PATTERN = re.compile(r"^Version: v(\d+\.\d+\.\d+)$", re.MULTILINE)

VERSION_FILE = Path("version")
PACKAGE_JSON = Path("package.json")
PY_MODULE = Path("python/qq_notifier.py")
TRACKED_FILES = (VERSION_FILE, PACKAGE_JSON, PY_MODULE)

ROOT = Path(__file__).resolve().parent.parent


class VersionError(RuntimeError):
    """Raised when the version sources are missing or malformed."""


def validate_version(value: str) -> str:
    if not isinstance(value, str) or not VERSION_PATTERN.match(value):
        raise VersionError(
            f"invalid version {value!r}; expected vMAJOR.MINOR.PATCH with integers >= 0"
        )
    return value


def bare(version: str) -> str:
    return validate_version(version)[1:]


def read_version_file(root: Path) -> str:
    path = root / VERSION_FILE
    if not path.exists():
        raise VersionError(f"missing {path}")
    return validate_version(path.read_text(encoding="utf-8").strip())


def read_package_version(root: Path) -> str:
    path = root / PACKAGE_JSON
    if not path.exists():
        raise VersionError(f"missing {path}")
    data = json.loads(path.read_text(encoding="utf-8"))
    value = data.get("version")
    if not isinstance(value, str):
        raise VersionError(f"{path} has no string 'version'")
    validate_version(f"v{value}")
    return value


def read_module_version(root: Path) -> str:
    path = root / PY_MODULE
    if not path.exists():
        raise VersionError(f"missing {path}")
    match = MODULE_VERSION_PATTERN.search(path.read_text(encoding="utf-8"))
    if not match:
        raise VersionError(f"{path} has no __version__")
    validate_version(f"v{match.group(1)}")
    return match.group(1)


def read_docstring_version(root: Path) -> str:
    path = root / PY_MODULE
    match = DOCSTRING_VERSION_PATTERN.search(path.read_text(encoding="utf-8"))
    if not match:
        raise VersionError(f"{path} has no 'Version: vX.Y.Z' docstring line")
    validate_version(f"v{match.group(1)}")
    return match.group(1)


def write_atomic(path: Path, text: str) -> None:
    temp = path.with_name(f"{path.name}.tmp-version")
    with temp.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)
    temp.replace(path)


def set_python_versions(text: str, version: str) -> str:
    display = f"v{version}"
    if MODULE_VERSION_PATTERN.search(text):
        text = MODULE_VERSION_PATTERN.sub(f'__version__ = "{version}"', text, count=1)
    else:
        anchor = "\n__all__ = ["
        if anchor not in text:
            raise VersionError("cannot find '__all__' in the python module")
        text = text.replace(anchor, f'\n__version__ = "{version}"\n\n__all__ = [', 1)

    if DOCSTRING_VERSION_PATTERN.search(text):
        text = DOCSTRING_VERSION_PATTERN.sub(f"Version: {display}", text, count=1)
    else:
        opening = text.find('"""')
        if opening < 0:
            raise VersionError("cannot find the module docstring")
        line_end = text.find("\n", opening)
        if line_end < 0:
            raise VersionError("cannot find the end of the docstring summary line")
        text = text[: line_end + 1] + f"\nVersion: {display}\n" + text[line_end + 1 :]
    return text


def update(root: Path, version: str, dry_run: bool = False) -> list:
    """Rewrite the derived files. Returns the repository-relative paths changed."""
    version = validate_version(version)
    numeric = bare(version)
    changed = []

    version_path = root / VERSION_FILE
    expected = f"{version}\n"
    if not version_path.exists() or version_path.read_text(encoding="utf-8") != expected:
        changed.append(VERSION_FILE.as_posix())
        if not dry_run:
            write_atomic(version_path, expected)

    package_path = root / PACKAGE_JSON
    package_text = package_path.read_text(encoding="utf-8")
    package = json.loads(package_text)
    if package.get("version") != numeric:
        package["version"] = numeric
        changed.append(PACKAGE_JSON.as_posix())
        if not dry_run:
            write_atomic(package_path, f"{json.dumps(package, indent=2)}\n")

    module_path = root / PY_MODULE
    module_text = module_path.read_text(encoding="utf-8")
    module_updated = set_python_versions(module_text, numeric)
    if module_updated != module_text:
        changed.append(PY_MODULE.as_posix())
        if not dry_run:
            write_atomic(module_path, module_updated)

    return changed


def git(root: Path, *args: str) -> subprocess.CompletedProcess:
    return subprocess.run(
        ["git", "-C", str(root), *args],
        capture_output=True,
        text=True,
        check=True,
    )


def is_git_repository(root: Path) -> bool:
    try:
        git(root, "rev-parse", "--git-dir")
        return True
    except (OSError, subprocess.CalledProcessError):
        return False


def tag_exists(root: Path, tag: str) -> bool:
    if not is_git_repository(root):
        raise VersionError(f"{root} is not a git repository")
    result = git(root, "tag", "--list", tag)
    return bool(result.stdout.strip())


def create_tag(root: Path, version: str) -> None:
    paths = [path.as_posix() for path in TRACKED_FILES]
    git(root, "add", "--", *paths)
    # --only keeps unrelated staged work out of the release commit.
    git(root, "commit", "--only", "-m", f"chore: release {version}", "--", *paths)
    git(root, "tag", "-a", version, "-m", version)


def check(root: Path, out=sys.stdout) -> int:
    current = read_version_file(root)
    numeric = bare(current)
    rows = (
        (VERSION_FILE.as_posix(), current, current),
        (PACKAGE_JSON.as_posix(), read_package_version(root), numeric),
        ("__version__", read_module_version(root), numeric),
        ("docstring", f"v{read_docstring_version(root)}", current),
    )
    ok = True
    print(f"current version: {current}\n", file=out)
    print(f"{'source':<14} {'actual':<10} {'expected':<10} status", file=out)
    for label, actual, expected in rows:
        status = "OK" if actual == expected else "MISMATCH"
        ok = ok and actual == expected
        print(f"{label:<14} {actual:<10} {expected:<10} {status}", file=out)

    if is_git_repository(root):
        state = "present" if tag_exists(root, current) else "missing"
    else:
        state = "unknown (not a git repository)"
    print(f"{'git tag ' + current:<14} {state}", file=out)
    return 0 if ok else 1


def run_update(root: Path, version: str, dry_run: bool, tag: bool, out=sys.stdout) -> int:
    version = validate_version(version)
    if tag and not dry_run and tag_exists(root, version):
        raise VersionError(f"tag {version} already exists")

    changed = update(root, version, dry_run=dry_run)
    if not changed:
        print(f"already at {version}; nothing to update", file=out)
        if tag and not dry_run:
            print("tag not created because nothing changed", file=out)
        return 0

    if dry_run:
        print(f"would update to {version}:", file=out)
        for path in changed:
            print(f"  {path}", file=out)
        return 0

    print(f"updated to {version}:", file=out)
    for path in changed:
        print(f"  {path}", file=out)

    if check(root, out=out) != 0:
        raise VersionError("version check failed after update")
    if tag:
        create_tag(root, version)
        print(f"committed and tagged {version}", file=out)
    return 0


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description="Manage the qq-notifier version.")
    subparsers = parser.add_subparsers(dest="command", required=True)

    subparsers.add_parser("check", help="report drift between the version file and derived files")

    update_parser = subparsers.add_parser("update", help="write a new version to every derived file")
    update_parser.add_argument("version", help="vMAJOR.MINOR.PATCH")
    update_parser.add_argument("--dry-run", action="store_true", help="print the plan, write nothing")
    update_parser.add_argument("--tag", action="store_true", help="commit the version files and tag the release")

    args = parser.parse_args(argv)
    try:
        if args.command == "check":
            return check(ROOT)
        return run_update(ROOT, args.version, args.dry_run, args.tag)
    except VersionError as error:
        print(f"error: {error}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
